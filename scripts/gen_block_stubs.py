"""gen_block_stubs — make `blocks.bck_xxx` in a book.py clickable in Cursor (go to definition, hover).

Each modules/<module>/blocks/__init__.py loads blocks lazily (`__getattr__` + streamtex ProjectBlockRegistry): one
line per block in book.py, no import to write. Static analysis does not run that code, so `blocks.bck_xxx` is seen
as a plain object with no file behind it. This tool writes, next to each __init__.py, an `__init__.pyi` read by the
editor only: it declares every local block as a submodule, so a click opens the block file. Nothing changes at run
time (the .pyi is never imported). Blocks found only in modules/shared-blocks/blocks stay declared through
`__getattr__` (no click: that folder is also named `blocks`).

Run it after adding or renaming a block (NG, 2026-11-22 — "OK pour la solution rapide avec le script"):

    uv run python scripts/gen_block_stubs.py
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = '''"""Editor-only declarations of this module's blocks — GENERATED by scripts/gen_block_stubs.py, do not edit.

Makes `blocks.bck_xxx` clickable in book.py; run time uses __init__.py (lazy ProjectBlockRegistry), never this file.
"""
from types import ModuleType

from streamtex import BlockImportError as BlockImportError
from streamtex import BlockNotFoundError as BlockNotFoundError
from streamtex import ProjectBlockRegistry

'''
FOOTER = '''
registry: ProjectBlockRegistry
__all__: list[str]


def __getattr__(name: str) -> ModuleType: ...   # blocks of modules/shared-blocks/blocks, resolved at run time
def __dir__() -> list[str]: ...
'''


def main() -> int:
    for init in sorted(ROOT.glob("modules/*/blocks/__init__.py")):
        if "def __getattr__" not in init.read_text(encoding="utf-8"):
            continue                       # not a lazy registry: nothing to declare
        names = sorted(p.stem for p in init.parent.glob("bck_*.py"))
        lines = [f"from . import {n} as {n}" for n in names]
        stub = init.with_suffix(".pyi")
        stub.write_text(HEADER + "\n".join(lines) + "\n" + FOOTER, encoding="utf-8")
        print(f"{stub.relative_to(ROOT)}: {len(names)} blocks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
